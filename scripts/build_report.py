# -*- coding: utf-8 -*-
"""제조본부장 현장 경영지시사항 보고서 (우주태양광) 생성기.

구조: 표제 + 4단계 계층 본문(1./1)/①/a)) + 표 3종 + 로드맵 이미지.
서술 밀도는 상무(경영층) 보고 스타일 — 각 ① 항목은 판단 근거까지 담은 완결 문장,
구조화된 세부(BOM)는 서술형 병합 표로 제시한다.
번호는 report_style 엔진이 자동 부여·리셋한다(호출부에서 번호를 넘기지 않음).
로드맵 이미지는 scripts/build_roadmap.py 로 먼저 생성해 둔다.
"""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
import report_style as S

HERE = os.path.dirname(__file__)
ROADMAP = os.path.abspath(os.path.join(HERE, "..", "assets", "roadmap.png"))

# ── 표1: PVA 소싱 → 내재화 전환 ──────────────────────────────────
PVA_SOURCING = {
    "headers": ["구분", "~'28", "'29~"],
    "rows": [
        ["PVA 제작",   "외주 소싱",                 "내재화 전환"],
        ["설계 소유권", "소싱 방식 검토중",           "자사 보유"],
        ["연동 사유",   "실증 단계·조달 리드타임 확보", "flight heritage 진입·캡티브 공급 개시"],
        ["관리 필요",   "외주 사양·표준 정합",         "델타 인증 부담 관리"],
    ],
}

# ── 표2: 1차 발사 슬롯 및 PVA 협력 현황 ─────────────────────────
PVA_PARTNER = {
    "headers": ["발사 슬롯", "일정", "패키징(PVA) 수행기관", "국가"],
    "rows": [
        ["1차", "'27년 2월", "University of Potsdam", "독일"],
    ],
}

# ── 표3: BOM 항목별 내재화/외주 구분 (서술형, 축 열 세로 병합) ────
BOM_RNR = {
    "headers": ["순번", "축", "BOM 항목", "세부 내용(구분·근거)"],
    "rows": [
        ["1", "CIC 공정",   "IV 분류",         "셀 특성 선별 공정, 자사 내재화 가능(설비·노하우 보유 전제)"],
        ["2", "CIC 공정",   "인터커넥터 용접",   "접합 신뢰성 핵심 공정, 내재화 우선 검토"],
        ["3", "CIC 공정",   "접착 코팅",        "봉지재 화학과 직결, 리스크 관리 대상·초기 외주 병행"],
        ["4", "CIC 공정",   "커버글라스 접합",   "방사선 차폐·방습 배리어와 통합 설계, 사양 자사 주도"],
        ["5", "CIC 공정",   "경화·검사",        "최종 품질 게이트, 내재화 필수"],
        ["6", "특화 리스크", "봉지재/배리어/온도/인터커넥션",
                            "탠덤 특화 4대 리스크, 항목별 사양 확정 후 Make/Buy 결정"],
    ],
}


def build(path):
    doc = S.new_document()
    S.title(doc, "제조본부장 현장 경영지시사항 보고")

    # 1. PVA 및 셀 설계 전략 구체화
    S.h1(doc, "PVA 및 셀 설계 전략 구체화")

    # 1) PVA 확보 전략
    S.h2(doc, "PVA 확보 전략")
    S.h3(doc, "국내에 우주급 PVA(태양전지 패키징) 국산화 인프라가 부재한 현 단계에서는, "
              "'28년까지 외주 소싱을 기반으로 사양·표준 정합성을 우선 확보하고, "
              "설계 소유권은 자사가 주도하여 내재화 전환 시 재설계 부담이 발생하지 않도록 관리한다.")
    S.h3(doc, "내재화 전환의 트리거는 단순 시점이 아니라 궤도 실증을 통한 flight heritage 확보이며, "
              "신뢰성이 입증되는 '29년을 기점으로 캡티브(자사) 공급 체계로 전환하여 "
              "조달 리드타임과 공급 안정성을 동시에 확보한다.")
    S.shaded_table(doc, PVA_SOURCING["headers"], PVA_SOURCING["rows"], emphasis_rows=[0])
    S.h3(doc, "'27년 2월 1차 발사 슬롯을 확보하였으며, 내재화 이전 단계인 만큼 첫 PVA 패키징은 "
              "검증된 해외 기관인 University of Potsdam(독일)에서 수행하여 발사 일정 리스크를 최소화한다.")
    S.shaded_table(doc, PVA_PARTNER["headers"], PVA_PARTNER["rows"])
    S.h3(doc, "국내 공급망 이관을 위해 국내 업체 솔랩과 협의를 진행할 계획이며, 기술 검증은 "
              "한서대학교 이훈희 교수와 협력하여 1차 발사 병행 중 국내 협력선을 육성한다.")

    # 2) BOM 구성 방향
    S.h2(doc, "BOM 구성 방향")
    S.h3(doc, "우주태양광 BOM은 CIC(Cell-Interconnect-Coverglass) 5단계 공정 순서를 뼈대로 구성하며, "
              "탠덤 셀 특화 리스크 4종(봉지재 화학 안정성·방습 배리어 성능·공정온도 상한·인터커넥션 방식)을 "
              "별도 관리 축으로 두어 수율·신뢰성 병목을 사전 통제한다.")
    S.h3(doc, "각 BOM 항목은 아래 표와 같이 '내재화 가능 / 외주 필요'로 구분하여 "
              "PVA 내재화 로드맵과 정합시킨다.")
    S.rnr_table(doc, BOM_RNR["headers"], BOM_RNR["rows"], merge_cols=[1])

    # 3) 셀 설계 방향 및 방사선 차폐 전략
    S.h2(doc, "셀 설계 방향 및 방사선 차폐 전략")
    S.h3(doc, "셀 사이즈·매수는 CIC·PVA·차폐·인증 시험이 순차 확정되는 인증 캐스케이드 전체의 "
              "핵심 병목이나 현재 미확정 상태이며, 이 결정이 지연되면 후속 일정 전체가 연쇄 지연되므로 "
              "최우선 의사결정 항목으로 상신한다.")
    S.h3(doc, "방사선 차폐는 별도 차폐층으로 접근하지 않고 BOM 상의 커버글라스·방습 배리어 사양과 "
              "통합 설계하여, 추가 중량·공정을 최소화하면서 차폐 요구를 흡수하는 방향으로 가설을 수립한다.")
    S.h3(doc, "검증 계획은 셀 사양 확정 → 시험 항목 확정 → 시험 순서(캐스케이드) 확정 순으로 정의하며, "
              "'27.12 지상 우주환경 인증을 앵커로 삼아 각 시험 시점을 역산 배치한다.")

    # 4) 종합 로드맵 및 후속 조치
    S.h2(doc, "종합 로드맵 및 후속 조치")
    S.h3(doc, "'27.12 지상 우주환경 인증을 앵커로 삼아 '27.2 1차 발사 → '27.12 인증 → "
              "'29~ flight heritage·내재화 전환의 세 마일스톤에 셀·CIC·PVA·인증 트랙을 정렬하고 "
              "전 일정을 역산 관리한다.")
    S.h3(doc, "경영층 의사결정이 필요한 항목은 두 가지로, (1) PVA Make/Buy 전환 시점을 '29년으로 "
              "고정할지 flight heritage 실제 확보 시점에 연동할지, (2) 인증 캐스케이드의 병목인 "
              "셀 사이즈·매수 확정이다.")
    S.h3(doc, "정합성 관리는 외주 구간의 외주사 사양·자사 표준 정합과, 내재화 전환 구간의 "
              "공급원 변경에 따른 델타(변경) 인증 부담을 전 기간에 걸쳐 지속 점검한다.")
    if os.path.exists(ROADMAP):
        S.image(doc, ROADMAP, width_cm=16.5)

    doc.save(path)
    print("saved:", path)


if __name__ == "__main__":
    build("/home/user/Report/제조본부장_현장경영지시사항_보고서.docx")
